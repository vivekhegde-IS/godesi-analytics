-- ============================================
-- GoDesi Analytics: Snowflake setup
-- Rerunnable: safe to run multiple times
-- ============================================

-- 1. WAREHOUSE        (role: SYSADMIN)
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS GODESI_WH
    WITH
    WAREHOUSE_SIZE      = 'XSMALL'
    AUTO_SUSPEND        = 60
    AUTO_RESUME         = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT             = 'Compute for GoDesi: loading, dbt builds and dashboards';


-- 2. DATABASES        (role: SYSADMIN)
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS GODESI_RAW
    COMMENT = 'Bronze layer: untouched source data, loaded as-is';

CREATE DATABASE IF NOT EXISTS GODESI_ANALYTICS
    COMMENT = 'Silver and gold layers: models built by dbt';


-- 3. SCHEMAS          (role: SYSADMIN)
USE ROLE SYSADMIN;

-- raw (bronze): one schema per source system
CREATE SCHEMA IF NOT EXISTS GODESI_RAW.ERP             COMMENT = 'Products, distributors, stores, promotions, offline orders';
CREATE SCHEMA IF NOT EXISTS GODESI_RAW.ECOM            COMMENT = 'D2C website customers and orders';
CREATE SCHEMA IF NOT EXISTS GODESI_RAW.MARKETPLACE     COMMENT = 'Amazon, Flipkart and quick-commerce orders';
CREATE SCHEMA IF NOT EXISTS GODESI_RAW.INVENTORY       COMMENT = 'Daily warehouse stock levels';
CREATE SCHEMA IF NOT EXISTS GODESI_RAW.OPEN_FOOD_FACTS COMMENT = 'Real product data from Open Food Facts (ODbL)';

-- analytics (silver/gold): one schema per dbt layer, plus a dev sandbox
CREATE SCHEMA IF NOT EXISTS GODESI_ANALYTICS.DBT_DEV_HEGDE COMMENT = 'Personal dev sandbox for dbt';
CREATE SCHEMA IF NOT EXISTS GODESI_ANALYTICS.STAGING       COMMENT = 'Silver: cleaned 1:1 source models';
CREATE SCHEMA IF NOT EXISTS GODESI_ANALYTICS.INTERMEDIATE  COMMENT = 'Silver: joined and enriched models';
CREATE SCHEMA IF NOT EXISTS GODESI_ANALYTICS.MARTS         COMMENT = 'Gold: star schema and business marts for BI';
CREATE SCHEMA IF NOT EXISTS GODESI_ANALYTICS.SNAPSHOTS     COMMENT = 'Price history (SCD Type 2)';


-- 4. ROLES            (role: USERADMIN, then SECURITYADMIN)
USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS LOADER      COMMENT = 'Loads raw files into GODESI_RAW';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'Used by dbt: reads RAW, builds GODESI_ANALYTICS';
CREATE ROLE IF NOT EXISTS REPORTER    COMMENT = 'Used by BI tools: reads MARTS only';

-- role hierarchy: custom roles roll up to SYSADMIN
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;

-- let my own user switch into each role (for testing)
-- granting to a user needs MANAGE GRANTS, which SECURITYADMIN has
-- the user name is lowercase, so it must be in double quotes
USE ROLE SECURITYADMIN;
GRANT ROLE LOADER      TO USER "hegdevivek379";
GRANT ROLE TRANSFORMER TO USER "hegdevivek379";
GRANT ROLE REPORTER    TO USER "hegdevivek379";


-- 5. GRANTS           (role: SECURITYADMIN)
-- SECURITYADMIN has MANAGE GRANTS: it can grant anything, including FUTURE grants
USE ROLE SECURITYADMIN;

-- 5a. Warehouse: every role may run queries on GODESI_WH
GRANT USAGE ON WAREHOUSE GODESI_WH TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE GODESI_WH TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE GODESI_WH TO ROLE REPORTER;

-- 5b. LOADER: create and load tables, stages and file formats in GODESI_RAW
GRANT USAGE ON DATABASE GODESI_RAW TO ROLE LOADER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE GODESI_RAW TO ROLE LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA GODESI_RAW.ERP             TO ROLE LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA GODESI_RAW.ECOM            TO ROLE LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA GODESI_RAW.MARKETPLACE     TO ROLE LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA GODESI_RAW.INVENTORY       TO ROLE LOADER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA GODESI_RAW.OPEN_FOOD_FACTS TO ROLE LOADER;

-- 5c. TRANSFORMER: read everything in GODESI_RAW (tables existing now AND created later)
GRANT USAGE ON DATABASE GODESI_RAW TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE GODESI_RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GODESI_RAW.ERP             TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GODESI_RAW.ERP             TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GODESI_RAW.ECOM            TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GODESI_RAW.ECOM            TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GODESI_RAW.MARKETPLACE     TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GODESI_RAW.MARKETPLACE     TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GODESI_RAW.INVENTORY       TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GODESI_RAW.INVENTORY       TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GODESI_RAW.OPEN_FOOD_FACTS TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GODESI_RAW.OPEN_FOOD_FACTS TO ROLE TRANSFORMER;

-- 5d. TRANSFORMER: build in GODESI_ANALYTICS (dbt drops and recreates objects, so it owns the schemas)
GRANT USAGE, CREATE SCHEMA ON DATABASE GODESI_ANALYTICS TO ROLE TRANSFORMER;
GRANT OWNERSHIP ON SCHEMA GODESI_ANALYTICS.DBT_DEV_HEGDE TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA GODESI_ANALYTICS.STAGING       TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA GODESI_ANALYTICS.INTERMEDIATE  TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA GODESI_ANALYTICS.MARTS         TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA GODESI_ANALYTICS.SNAPSHOTS     TO ROLE TRANSFORMER COPY CURRENT GRANTS;

-- 5e. REPORTER: read MARTS only (tables and views, existing now AND created later)
GRANT USAGE ON DATABASE GODESI_ANALYTICS TO ROLE REPORTER;
GRANT USAGE ON SCHEMA GODESI_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GODESI_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GODESI_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA GODESI_ANALYTICS.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA GODESI_ANALYTICS.MARTS TO ROLE REPORTER;


-- 6. DBT SERVICE USER (role: USERADMIN, then SECURITYADMIN)
-- a service user: no password, no Snowsight login, key-pair auth only
USE ROLE USERADMIN;

CREATE USER IF NOT EXISTS DBT_USER
    TYPE              = SERVICE
    DEFAULT_ROLE      = TRANSFORMER
    DEFAULT_WAREHOUSE = GODESI_WH
    DEFAULT_NAMESPACE = GODESI_ANALYTICS.DBT_DEV_HEGDE
    COMMENT           = 'Service user for dbt Core (key-pair auth)';

-- run ONCE by hand in Snowflake with the real key from ~/.ssh/snowflake/rsa_key.pub
-- (one line, no BEGIN/END lines). Kept as a comment so a full rerun does not fail.
-- ALTER USER DBT_USER SET RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY_HERE>';

USE ROLE SECURITYADMIN;
GRANT ROLE TRANSFORMER TO USER DBT_USER;


-- 7. RESOURCE MONITOR (role: ACCOUNTADMIN)
-- a credit budget: warn at 75%, stop the warehouse at 100%
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE RESOURCE MONITOR GODESI_RM
    WITH
    CREDIT_QUOTA    = 20
    FREQUENCY       = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 75  PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND
        ON 110 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE GODESI_WH SET RESOURCE_MONITOR = GODESI_RM;


-- 8. VERIFICATION (run one at a time and read the output)
USE ROLE ACCOUNTADMIN;

SHOW WAREHOUSES LIKE 'GODESI_WH';                 -- resource_monitor = GODESI_RM
SHOW RESOURCE MONITORS LIKE 'GODESI_RM';          -- quota 20, monthly
SHOW SCHEMAS IN DATABASE GODESI_RAW;              -- ERP, ECOM, MARKETPLACE, INVENTORY, OPEN_FOOD_FACTS
SHOW SCHEMAS IN DATABASE GODESI_ANALYTICS;        -- owner = TRANSFORMER for the 5 dbt schemas
SHOW GRANTS TO ROLE LOADER;
SHOW GRANTS TO ROLE TRANSFORMER;
SHOW GRANTS TO ROLE REPORTER;
SHOW FUTURE GRANTS IN SCHEMA GODESI_ANALYTICS.MARTS;
DESC USER DBT_USER;                               -- TYPE = SERVICE, RSA_PUBLIC_KEY_FP = SHA256:...
SHOW GRANTS TO USER DBT_USER;                     -- TRANSFORMER
